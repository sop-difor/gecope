-- Migração: equivalências confirmadas na Conferência Orçamentária (Curva ABC)
--
-- Contexto: a Conferência Orçamentária cruza o orçamento aprovado pela fiscalização com
-- o orçamento revisado pela SOP (biblioteca de Orçamentos). O cruzamento é recalculado a
-- cada abertura da tela e NÃO é gravado. A única coisa que vai para o banco é a decisão
-- do analista de que um serviço do aprovado equivale a um ou mais serviços do revisado
-- quando o sistema não conseguiu garantir isso sozinho (código diferente, unidade
-- diferente, descrição parecida). Só essas equivalências somam códigos diferentes.
--
-- `fisc_chave` e `rev_chaves[].chave` são as chaves de agrupamento do motor
-- (modules/curva-abc/conferencia_motor.js): "C|<código>|<unidade>" ou
-- "D|<descrição normalizada>|<unidade>". A equivalência vale para o processo inteiro,
-- em qualquer versão da Curva ABC. Se o orçamento revisado escolhido mudar e a chave
-- não existir nele, a equivalência é simplesmente ignorada.
--
-- Permissões: mesmas funções das demais tabelas curva_abc_* (ler: admin/gerente/fiscal;
-- escrever: admin/gerente). Seguro rodar de novo.

begin;

create table if not exists curva_abc_equivalencias (
  id            bigint generated by default as identity primary key,
  processo_id   text not null,
  fisc_chave    text not null,
  fisc_codigo   text,
  fisc_descricao text,
  rev_chaves    jsonb not null,          -- [{ "chave": "...", "codigo": "...", "descricao": "...", "un": "..." }]
  orcamento_id  bigint,                  -- orcamentos_biblioteca.id usado quando foi confirmada
  autor_nome    text not null,
  autor_email   text,
  created_at    timestamptz not null default now(),
  unique (processo_id, fisc_chave)
);

create index if not exists idx_curva_abc_equivalencias_processo on curva_abc_equivalencias (processo_id);

alter table curva_abc_equivalencias enable row level security;

drop policy if exists "curva_abc_equivalencias_select" on curva_abc_equivalencias;
create policy "curva_abc_equivalencias_select" on curva_abc_equivalencias
  for select using (curva_abc_pode_ler());

drop policy if exists "curva_abc_equivalencias_insert" on curva_abc_equivalencias;
create policy "curva_abc_equivalencias_insert" on curva_abc_equivalencias
  for insert with check (curva_abc_pode_escrever());

drop policy if exists "curva_abc_equivalencias_update" on curva_abc_equivalencias;
create policy "curva_abc_equivalencias_update" on curva_abc_equivalencias
  for update using (curva_abc_pode_escrever()) with check (curva_abc_pode_escrever());

drop policy if exists "curva_abc_equivalencias_delete" on curva_abc_equivalencias;
create policy "curva_abc_equivalencias_delete" on curva_abc_equivalencias
  for delete using (curva_abc_pode_escrever());

commit;

